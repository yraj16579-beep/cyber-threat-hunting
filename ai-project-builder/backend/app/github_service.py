import httpx
from .config import settings

API = "https://api.github.com"
HEADERS_BASE = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}

class GitHubError(RuntimeError):
    pass

async def github_request(method, path, token, **kwargs):
    headers = {**HEADERS_BASE, "Authorization": f"Bearer {token}", **kwargs.pop("headers", {})}
    async with httpx.AsyncClient(timeout=45) as client:
        r = await client.request(method, f"{API}{path}", headers=headers, **kwargs)
    if r.status_code >= 400:
        try:
            message = r.json().get("message", r.text)
        except Exception:
            message = r.text
        raise GitHubError(f"GitHub API returned {r.status_code}: {message}")
    return r.json() if r.content else {}

async def list_repositories(token):
    result = []
    page = 1
    while page <= 3:
        data = await github_request("GET", "/user/repos", token, params={"per_page": 100, "page": page, "sort": "updated"})
        result.extend(data)
        if len(data) < 100:
            break
        page += 1
    return [{"full_name": r["full_name"], "private": r["private"], "html_url": r["html_url"], "default_branch": r.get("default_branch") or "main"} for r in result]

async def publish_files(token, owner, repo, branch, files, create_repo=False, description="", private=False):
    if create_repo:
        await github_request("POST", "/user/repos", token, json={
            "name": repo, "description": description, "private": private, "auto_init": True
        })
    # Resolve repository and branch. For empty/new repositories, create an initial commit.
    repository = await github_request("GET", f"/repos/{owner}/{repo}", token)
    try:
        ref = await github_request("GET", f"/repos/{owner}/{repo}/git/ref/heads/{branch}", token)
        parent_sha = ref["object"]["sha"]
        base_tree = (await github_request("GET", f"/repos/{owner}/{repo}/git/commits/{parent_sha}", token))["tree"]["sha"]
    except GitHubError as exc:
        if "404" not in str(exc):
            raise
        # New branch from default branch if available; otherwise create root commit.
        default_branch = repository.get("default_branch") or "main"
        try:
            default_ref = await github_request("GET", f"/repos/{owner}/{repo}/git/ref/heads/{default_branch}", token)
            parent_sha = default_ref["object"]["sha"]
            base_tree = (await github_request("GET", f"/repos/{owner}/{repo}/git/commits/{parent_sha}", token))["tree"]["sha"]
        except GitHubError:
            blob = await github_request("POST", f"/repos/{owner}/{repo}/git/blobs", token, json={"content": "Generated by AI Project Builder\\n", "encoding": "utf-8"})
            tree = await github_request("POST", f"/repos/{owner}/{repo}/git/trees", token, json={"tree": [{"path": "README.md", "mode": "100644", "type": "blob", "sha": blob["sha"]}]})
            commit = await github_request("POST", f"/repos/{owner}/{repo}/git/commits", token, json={"message": "Initialize repository", "tree": tree["sha"], "parents": []})
            await github_request("POST", f"/repos/{owner}/{repo}/git/refs", token, json={"ref": f"refs/heads/{branch}", "sha": commit["sha"]})
            parent_sha, base_tree = commit["sha"], tree["sha"]
        if branch != default_branch:
            await github_request("POST", f"/repos/{owner}/{repo}/git/refs", token, json={"ref": f"refs/heads/{branch}", "sha": parent_sha})
    tree_entries = []
    for path, content in files.items():
        blob = await github_request("POST", f"/repos/{owner}/{repo}/git/blobs", token, json={"content": content, "encoding": "utf-8"})
        tree_entries.append({"path": path, "mode": "100644", "type": "blob", "sha": blob["sha"]})
    tree = await github_request("POST", f"/repos/{owner}/{repo}/git/trees", token, json={"base_tree": base_tree, "tree": tree_entries})
    commit = await github_request("POST", f"/repos/{owner}/{repo}/git/commits", token, json={
        "message": "Publish generated project with AI Project Builder",
        "tree": tree["sha"], "parents": [parent_sha]
    })
    try:
        await github_request("PATCH", f"/repos/{owner}/{repo}/git/refs/heads/{branch}", token, json={"sha": commit["sha"], "force": False})
    except GitHubError as exc:
        if "404" in str(exc):
            await github_request("POST", f"/repos/{owner}/{repo}/git/refs", token, json={"ref": f"refs/heads/{branch}", "sha": commit["sha"]})
        else:
            raise
    return {"url": repository["html_url"], "commit_url": f'{repository["html_url"]}/commit/{commit["sha"]}', "commit_sha": commit["sha"]}
